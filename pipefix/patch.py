"""Turn diagnoses into a Nextflow config change, informed by the repo's config trace and the AWS platform.

All fixes go into one file, conf/pipefix.config, included at the END of nextflow.config so it overrides the
pipeline's defaults. Each fix is a `withName:` block scoped to the one process that failed. Before writing a
fix pipefix checks:
  * the process exists in the repo (a selector that matches nothing would be a silent no-op);
  * the new memory fits the largest instance the Batch queue can launch (else the job could never start);
  * resource caps (resourceLimits / params.max_memory) that would silently clip the new value;
  * an existing errorStrategy that already retries (kept rather than replaced).
Re-running pipefix updates the same blocks instead of piling up duplicates.
"""
from __future__ import annotations

import difflib
import re
from dataclasses import dataclass, field
from pathlib import Path

from .configtrace import ProcessTrace, RepoConfig, _Parser, grows_with_attempt, load_repo, memory_literal_bytes
from .investigation import Finding, Investigation
from .models import Diagnosis, FailureClass
from .units import ceil_gb, ceil_hours, gb

CONFIG_REL = "conf/pipefix.config"
INCLUDE_LINE = f"includeConfig '{CONFIG_REL}'"
# nf-core's default retry set (130..145 kill/signal codes, 104 connection reset, 175..177 Java) plus 247
RETRY_EXPR = "{ task.exitStatus in ((130..145) + 104 + (175..177) + 247) ? 'retry' : 'finish' }"
MIB = 1024**2


@dataclass
class ProcessFix:
    name: str
    settings: dict[str, str] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)


@dataclass
class Patch:
    files: dict[str, tuple[str, str]]          # rel path -> (old, new)
    fixes: list[ProcessFix]
    advisories: list[Diagnosis]                 # diagnosed, but not safely fixable by pipeline config
    global_settings: dict[str, str]
    findings: list[Finding] = field(default_factory=list)
    traces: dict[str, ProcessTrace] = field(default_factory=dict)
    ai: object = None                           # research.AIResult when the AI researched the fix
    ai_used: list[str] = field(default_factory=list)   # processes whose fix came from the AI

    @property
    def empty(self) -> bool:
        return not any(old != new for old, new in self.files.values())

    def diff(self) -> str:
        out = []
        for rel, (old, new) in self.files.items():
            if old == new:
                continue
            out += difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                                        fromfile=f"a/{rel}" if old else "/dev/null", tofile=f"b/{rel}")
        return "".join(out)

    def apply(self, repo: str | Path) -> list[str]:
        written = []
        for rel, (old, new) in self.files.items():
            if old != new:
                p = Path(repo) / rel
                p.parent.mkdir(parents=True, exist_ok=True)
                # keep the file's own line endings (CRLF repos on Windows stay CRLF; new files get LF)
                eol = "\r\n" if p.exists() and b"\r\n" in p.read_bytes() else "\n"
                p.write_text(new, encoding="utf-8", newline=eol)
                written.append(rel)
        return written


# ---------- reading and writing conf/pipefix.config ----------

_BLOCK_HEAD = re.compile(r"withName\s*:\s*['\"]([^'\"]+)['\"]\s*\{")
_GLOBAL = re.compile(r"^\s*(aws\.batch\.maxSpotAttempts)\s*=\s*(.+?)\s*$", re.M)


def _read_existing(text: str, root: Path) -> tuple[dict[str, ProcessFix], dict[str, str]]:
    """Parse our own file with the real config parser, so hand edits (quotes, indentation, closures) survive."""
    blocks: dict[str, ProcessFix] = {}
    if not text.strip():
        return blocks, {}
    cfg = RepoConfig(root)
    p = _Parser(cfg)
    from .configtrace import _strip_comments
    p._block(_strip_comments(text), 0, [], CONFIG_REL, root, 0, "")
    for s in cfg.settings:
        if s.level == "withName":
            name = s.selector.split(":", 1)[1].strip().strip("'\"")
            blocks.setdefault(name, ProcessFix(name)).settings[s.directive] = s.value
    # keep the comment lines that follow each block header
    lines = text.splitlines()
    for i, ln in enumerate(lines):
        m = _BLOCK_HEAD.search(ln)
        if m and m.group(1) in blocks:
            for nxt in lines[i + 1:]:
                if not nxt.strip().startswith("//"):
                    break
                blocks[m.group(1)].notes.append(nxt.strip()[2:].strip())
    return blocks, {m.group(1): m.group(2) for m in _GLOBAL.finditer(text)}


def _render(blocks: dict[str, ProcessFix], global_settings: dict[str, str]) -> str:
    lines = ["// Generated by pipefix. Each block changes ONE process that failed; see the notes on each block.",
             "// Safe to edit by hand; pipefix updates blocks in place on later runs.", ""]
    for k, v in global_settings.items():
        lines.append(f"{k} = {v}")
    if global_settings:
        lines.append("")
    lines.append("process {")
    for name in sorted(blocks):
        b = blocks[name]
        lines.append(f"    withName: '{name}' {{")
        lines += [f"        // {note}" for note in b.notes]
        width = max((len(k) for k in b.settings), default=0)
        lines += [f"        {k.ljust(width)} = {v}" for k, v in b.settings.items()]
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


# ---------- the fixes ----------

def _cap_bytes(cfg: RepoConfig | None) -> tuple[int | None, str]:
    if not cfg or "memory" not in cfg.caps:
        return None, ""
    return memory_literal_bytes(cfg.caps["memory"]), cfg.cap_sources.get("memory", "")


def _retry_settings(fix: ProcessFix, tr: ProcessTrace | None, min_retries: int) -> None:
    es = tr.effective("errorStrategy") if tr else None
    if es and "retry" in es.value:
        fix.notes.append(f"keeps the existing retry rule from {es.where}")
    else:
        fix.settings["errorStrategy"] = RETRY_EXPR
    mr = tr.effective("maxRetries") if tr else None
    try:
        current = int(mr.value) if mr else 1
    except ValueError:
        current = 1
    if current < min_retries:
        fix.settings["maxRetries"] = str(min_retries)


def _memory_fix(d: Diagnosis, tr: ProcessTrace | None, cfg: RepoConfig | None, facts: dict,
                findings: list[Finding]) -> ProcessFix | None:
    f = d.failure
    fix = ProcessFix(f.simple_name)
    cur = tr.effective("memory") if tr else None
    req = f.memory_bytes or (memory_literal_bytes(cur.value) if cur else None)
    cands = [2 * req] if req else []
    if f.peak_rss_bytes:
        cands.append(int(f.peak_rss_bytes * 1.5))
    new_gb = ceil_gb(max(cands)) if cands else 16
    platform_max = facts.get("max_task_memory_mib")
    if platform_max:
        max_gb = int(platform_max * MIB / 1024**3)
        if req and req >= max_gb * 1024**3 * 0.95:
            findings.append(Finding("Already at the largest instance",
                                    f"{f.display} asked for {gb(req):.0f} GB and the queue's largest instance fits "
                                    f"about {max_gb} GB. More memory needs a larger instance type in the compute "
                                    "environment (or a smaller input chunk), not a config change.", "block",
                                    f.simple_name))
            return None
        if new_gb > max_gb:
            new_gb = max_gb
            fix.notes.append(f"capped at {max_gb} GB, the most the queue's largest instance can give a task")
    why = ("out of memory" + (f" at {gb(f.peak_rss_bytes):.1f} of {gb(req):.1f} GB" if f.peak_rss_bytes and req
                              else f" with {gb(req):.1f} GB requested" if req else ", requested amount unknown"))
    fix.notes.insert(0, f"pipefix: {why}; now {new_gb} GB, growing with each retry")
    if cur:
        fix.notes.append(f"was {cur.value.strip()} from {cur.where} ({cur.selector})")
    if platform_max:
        max_gb = int(platform_max * MIB / 1024**3)
        fix.settings["memory"] = f"{{ [{new_gb}.GB * task.attempt, {max_gb}.GB].min() }}"
    else:
        fix.settings["memory"] = f"{{ {new_gb}.GB * task.attempt }}"
    cap, where = _cap_bytes(cfg)
    if cap and cap < new_gb * 1024**3:
        findings.append(Finding("Resource cap will clip the new memory",
                                f"{where} caps memory at {gb(cap):.0f} GB, below the {new_gb} GB this fix sets. "
                                f"Raise that cap (e.g. --max_memory '{new_gb}.GB' or resourceLimits) or the "
                                "change has no effect.", "warn", f.simple_name))
    _retry_settings(fix, tr, 2)
    if re.search(r"gatk|picard|java", f.process, re.I):
        fix.notes.append("Java tool: nf-core GATK/Picard modules size -Xmx from task.memory, so the heap grows too")
    return fix


def _time_fix(d: Diagnosis, tr: ProcessTrace | None) -> ProcessFix:
    f = d.failure
    fix = ProcessFix(f.simple_name)
    cur = tr.effective("time") if tr else None
    cands = [2 * f.time_ms] if f.time_ms else []
    if f.realtime_ms:
        cands.append(int(f.realtime_ms * 1.5))
    hours = ceil_hours(max(cands)) if cands else 24
    fix.notes.append(f"pipefix: hit its time limit; now {hours} h, growing with each retry")
    if cur:
        fix.notes.append(f"was {cur.value.strip()} from {cur.where} ({cur.selector})")
    fix.settings["time"] = f"{{ {hours}.h * task.attempt }}"
    _retry_settings(fix, tr, 2)
    return fix


def _spot_fix(d: Diagnosis, tr: ProcessTrace | None, facts: dict, global_settings: dict) -> ProcessFix:
    f = d.failure
    fix = ProcessFix(f.simple_name)
    fix.notes.append("pipefix: Spot instance reclaimed by AWS"
                     + (f" ({f.spot_reclaims} of {f.attempts} attempts)" if f.spot_reclaims else "")
                     + "; AWS Batch now retries reclamations (aws.batch.maxSpotAttempts)")
    global_settings["aws.batch.maxSpotAttempts"] = "3"
    long_run = (f.realtime_ms or 0) >= 2 * 3_600_000
    od = (facts.get("ondemand_queues") or [None])[0]
    if od and (f.spot_reclaims >= 2 or long_run):
        fix.settings["queue"] = f"'{od}'"
        fix.notes.append(f"moved to On-Demand queue '{od}': "
                         + ("reclaimed repeatedly" if f.spot_reclaims >= 2 else "runs for hours, so a reclaim is costly"))
    elif long_run:
        fix.notes.append("long task on Spot: consider an On-Demand queue for it (none found in this account)")
    mr = tr.effective("maxRetries") if tr else None
    try:
        if not mr or int(mr.value) < 2:
            fix.settings["maxRetries"] = "2"
    except ValueError:
        pass
    return fix


def _ai_fix(aifx, ai, tr: ProcessTrace | None, rule: ProcessFix | None, findings: list[Finding]) -> ProcessFix:
    fix = ProcessFix(aifx.name, dict(aifx.settings))
    # the config comment stays short: what changes and the formula; the full reasoning is in the MR
    title = aifx.rationale.split(": ", 1)[0].strip()
    formulas = " ".join(re.findall(r"\[[^\]]{3,300}\]", aifx.rationale))
    short = title if len(title) <= 160 else title[:157] + "..."
    fix.notes.append(f"pipefix AI ({ai.model}): {short} {formulas}".strip())
    for directive in aifx.settings:
        cur = tr.effective(directive) if tr else None
        if cur:
            fix.notes.append(f"was {directive} {cur.value.strip()} from {cur.where} ({cur.selector})")
    fix.notes += [f"source [{s['n']}] {s['url']}" for s in ai.cite(aifx.sources)]
    if rule and rule.settings != fix.settings:
        findings.append(Finding("pipefix's rules would have fixed this differently",
                                "Rule-based fix: " + "; ".join(f"{k} = {v}" for k, v in rule.settings.items())
                                + ". The AI-researched fix above was used instead.", "info", aifx.name))
    return fix


_OWN_NOTES = ("pipefix:", "pipefix AI", "source [", "was ", "keeps ", "capped ", "moved ", "Java tool", "long task")


def build_patch(diagnoses: list[Diagnosis], repo: str | Path, min_confidence: float = 0.6,
                inv: Investigation | None = None, cfg: RepoConfig | None = None, profiles: tuple[str, ...] = (),
                ai=None) -> Patch:
    """`ai`: a research.AIResult; its checked fixes replace the rule-based ones for the processes they cover."""
    ai_by_name = {fx.name: fx for fx in (ai.fixes if ai else [])}
    ai_used: list[str] = []
    repo = Path(repo)
    cfg = cfg or load_repo(repo)
    facts = inv.facts if inv else {}
    cfg_path, main_path = repo / CONFIG_REL, repo / "nextflow.config"
    old_cfg = cfg_path.read_text(encoding="utf-8") if cfg_path.exists() else ""
    old_main = main_path.read_text(encoding="utf-8") if main_path.exists() else ""
    blocks, global_settings = _read_existing(old_cfg, repo)
    before = {k: dict(v.settings) for k, v in blocks.items()}
    globals_before = dict(global_settings)

    fixes, advisories, findings, traces = [], [], [], {}
    for d in diagnoses:
        f = d.failure
        # make sure the process exists in the repo before writing a selector for it
        approximate = f.context.get("process_name_source", "").startswith("job name")
        if (cfg.processes or approximate) and f.simple_name not in cfg.processes:
            hit = cfg.resolve_process(f.context.get("job_name") or f.process)
            if hit:
                old = f.simple_name
                f.process, f.tag = hit[0], f.tag or hit[1]
                f.context["process_name_source"] = "job name matched to the repo"
                for fd in (inv.findings if inv else []):
                    if fd.title == "Process name is approximate" and fd.process == old:
                        fd.severity, fd.process = "info", f.simple_name
                        fd.title = "Process matched from the job name"
                        fd.detail = (f"Batch job `{f.context.get('job_name')}` is `{f.simple_name}`, defined in "
                                     f"`{cfg.processes[f.simple_name][0]}`.")
            elif not f.process.startswith("("):
                findings.append(Finding("Process not found in this repo",
                                        f"`{f.process}` is not defined in any .nf file here, so no config was written "
                                        "for it (a selector that matches nothing would do nothing).", "warn",
                                        f.simple_name))
                advisories.append(d)
                continue
        tr = cfg.trace(f.process, profiles) if not f.process.startswith("(") else None
        if tr:
            traces[f.simple_name] = tr
        fix = None
        if d.cls.auto_fixable and d.confidence >= min_confidence and not f.process.startswith("("):
            if d.cls == FailureClass.OUT_OF_MEMORY:
                fix = _memory_fix(d, tr, cfg, facts, findings)
            elif d.cls == FailureClass.TIMEOUT:
                fix = _time_fix(d, tr)
            elif d.cls == FailureClass.SPOT_INTERRUPTION and f.source != "healthomics":
                fix = _spot_fix(d, tr, facts, global_settings)
        if f.simple_name in ai_by_name and not f.process.startswith("("):
            fix = _ai_fix(ai_by_name.pop(f.simple_name), ai, tr, fix, findings)
            ai_used.append(fix.name)
        if fix is None:
            advisories.append(d)
            continue
        cur = blocks.get(fix.name)
        if cur:  # merge into the existing block: keep its other settings, replace pipefix's own notes
            cur.settings.update(fix.settings)
            cur.notes = [n for n in cur.notes if not n.startswith(_OWN_NOTES)] + fix.notes
            fix = cur
        blocks[fix.name] = fix
        if fix not in fixes:
            fixes.append(fix)

    if facts.get("healthomics") and fixes:
        findings.append(Finding("Publish a new workflow version",
                                "HealthOmics runs a stored copy of the workflow. After merging, create a new version "
                                "(`aws omics create-workflow-version`) and start the next run from it.", "info"))
    changed = any(before.get(k) != v.settings for k, v in blocks.items()) or global_settings != globals_before
    new_cfg = _render(blocks, global_settings) if changed and (blocks or global_settings) else old_cfg
    new_main = old_main
    already = re.search(r"includeConfig\s+['\"]" + re.escape(CONFIG_REL) + r"['\"]", old_main)
    if new_cfg != old_cfg and not already:
        new_main = old_main.rstrip("\n") + ("\n\n" if old_main else "") + \
            f"// Fixes proposed by pipefix (keep this last so it overrides the defaults above)\n{INCLUDE_LINE}\n"
    return Patch({CONFIG_REL: (old_cfg, new_cfg), "nextflow.config": (old_main, new_main)},
                 fixes, advisories, global_settings, findings, traces, ai, ai_used)


