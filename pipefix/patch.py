"""Turn diagnoses into a Nextflow config change.

All fixes go into one file, conf/pipefix.config, included at the END of nextflow.config so it overrides the
pipeline's defaults. Each fix is a `withName:` block scoped to the one process that failed, so nothing else in the
pipeline changes. Re-running pipefix updates the same file instead of piling up duplicates.
"""
from __future__ import annotations

import difflib
import re
from dataclasses import dataclass, field
from pathlib import Path

from .models import Diagnosis, FailureClass
from .units import ceil_gb, ceil_hours

CONFIG_REL = "conf/pipefix.config"
INCLUDE_LINE = f"includeConfig '{CONFIG_REL}'"
RETRY_CODES = [104, 134, 137, 139, 140, 143, 247]  # common kill / OOM / scheduler exit codes


@dataclass
class ProcessFix:
    name: str
    settings: dict[str, str] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)


@dataclass
class Patch:
    files: dict[str, tuple[str, str]]          # rel path -> (old, new)
    fixes: list[ProcessFix]
    advisories: list[Diagnosis]                 # diagnosed, but not safely fixable by config
    global_settings: dict[str, str]

    @property
    def empty(self) -> bool:
        return not any(old != new for old, new in self.files.values())

    def diff(self) -> str:
        out = []
        for rel, (old, new) in self.files.items():
            if old == new:
                continue
            out += difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                                        fromfile=f"a/{rel}" if old else "/dev/null", tofile=f"b/{rel}")
        return "".join(out)

    def apply(self, repo: str | Path) -> list[str]:
        written = []
        for rel, (old, new) in self.files.items():
            if old != new:
                p = Path(repo) / rel
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(new, encoding="utf-8")
                written.append(rel)
        return written


# ---------- reading and writing conf/pipefix.config ----------

_BLOCK = re.compile(r"withName:\s*'(?P<name>[^']+)'\s*\{(?P<body>.*?)\n\s{4}\}", re.S)
_SETTING = re.compile(r"^\s*(?P<key>\w+)\s*=\s*(?P<val>.+?)\s*$")
_GLOBAL = re.compile(r"^(?P<key>aws\.[\w.]+)\s*=\s*(?P<val>.+?)\s*$", re.M)


def _read_existing(text: str) -> tuple[dict[str, ProcessFix], dict[str, str]]:
    blocks = {}
    for m in _BLOCK.finditer(text):
        fix = ProcessFix(m.group("name"))
        for ln in m.group("body").splitlines():
            if ln.strip().startswith("//"):
                fix.notes.append(ln.strip()[2:].strip())
            elif s := _SETTING.match(ln):
                fix.settings[s.group("key")] = s.group("val")
        blocks[fix.name] = fix
    return blocks, {m.group("key"): m.group("val") for m in _GLOBAL.finditer(text)}


def _render(blocks: dict[str, ProcessFix], global_settings: dict[str, str]) -> str:
    lines = ["// Generated by pipefix. Each block raises resources or retries for ONE process that failed.",
             "// Safe to edit by hand; pipefix updates blocks in place on later runs.", ""]
    for k, v in global_settings.items():
        lines.append(f"{k} = {v}")
    if global_settings:
        lines.append("")
    lines.append("process {")
    for name in sorted(blocks):
        b = blocks[name]
        lines.append(f"    withName: '{name}' {{")
        for note in b.notes:
            lines.append(f"        // {note}")
        width = max(len(k) for k in b.settings)
        for k, v in b.settings.items():
            lines.append(f"        {k.ljust(width)} = {v}")
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


# ---------- the fixes ----------

def _retry_strategy(codes: list[int]) -> dict[str, str]:
    return {"errorStrategy": f"{{ task.exitStatus in {codes} ? 'retry' : 'finish' }}", "maxRetries": "2"}


def _fix_for(d: Diagnosis) -> ProcessFix | None:
    f = d.failure
    fix = ProcessFix(f.simple_name)
    if d.cls == FailureClass.OUT_OF_MEMORY:
        candidates = [2 * f.memory_bytes] if f.memory_bytes else []
        if f.peak_rss_bytes:
            candidates.append(int(f.peak_rss_bytes * 1.5))
        if candidates:
            new_gb = ceil_gb(max(candidates))
            fix.notes.append(f"pipefix: out of memory"
                             + (f" at {f.peak_rss_bytes / 1024**3:.1f} of {f.memory_bytes / 1024**3:.1f} GB"
                                if f.peak_rss_bytes and f.memory_bytes else
                                f" with {f.memory_bytes / 1024**3:.1f} GB requested" if f.memory_bytes else "")
                             + f"; now {new_gb} GB, growing with each retry")
        else:
            new_gb = 16
            fix.notes.append("pipefix: out of memory, requested amount unknown; starting at 16 GB, review this")
        fix.settings["memory"] = f"{{ {new_gb}.GB * task.attempt }}"
        fix.settings.update(_retry_strategy(RETRY_CODES))
        if re.search(r"gatk|picard|java", f.process, re.I):
            fix.notes.append("Java tool: nf-core GATK/Picard modules size the JVM heap (-Xmx) from task.memory, "
                             "so raising memory also raises the heap")
    elif d.cls == FailureClass.SPOT_INTERRUPTION:
        fix.notes.append("pipefix: Spot instance reclaimed by AWS; retry instead of failing the whole run")
        # Nextflow leaves exitStatus at Integer.MAX_VALUE when the host vanished before the task reported one.
        fix.settings.update({"errorStrategy": f"{{ task.exitStatus in {RETRY_CODES} || "
                                              "task.exitStatus == Integer.MAX_VALUE ? 'retry' : 'finish' }",
                             "maxRetries": "3"})
    elif d.cls == FailureClass.TIMEOUT:
        candidates = [2 * f.time_ms] if f.time_ms else []
        if f.realtime_ms:
            candidates.append(int(f.realtime_ms * 1.5))
        hours = ceil_hours(max(candidates)) if candidates else 24
        fix.notes.append(f"pipefix: hit its time limit; now {hours} h, growing with each retry")
        fix.settings["time"] = f"{{ {hours}.h * task.attempt }}"
        fix.settings.update(_retry_strategy(RETRY_CODES))
    else:
        return None
    return fix


def build_patch(diagnoses: list[Diagnosis], repo: str | Path, min_confidence: float = 0.6) -> Patch:
    repo = Path(repo)
    cfg_path, main_path = repo / CONFIG_REL, repo / "nextflow.config"
    old_cfg = cfg_path.read_text(encoding="utf-8") if cfg_path.exists() else ""
    old_main = main_path.read_text(encoding="utf-8") if main_path.exists() else ""
    blocks, global_settings = _read_existing(old_cfg)
    blocks_before = {k: dict(v.settings) for k, v in blocks.items()}

    fixes, advisories = [], []
    for d in diagnoses:
        fix = _fix_for(d) if d.cls.auto_fixable and d.confidence >= min_confidence else None
        if fix is None:
            advisories.append(d)
            continue
        cur = blocks.get(fix.name)
        if cur:  # merge into the existing block: keep its other settings, replace pipefix's own notes
            cur.settings.update(fix.settings)
            cur.notes = [n for n in cur.notes if not n.startswith("pipefix:")] + fix.notes
            fix = cur
        blocks[fix.name] = fix
        fixes.append(fix)
        if d.cls == FailureClass.SPOT_INTERRUPTION and d.failure.source != "healthomics":
            global_settings["aws.batch.maxSpotAttempts"] = "3"

    changed = any(blocks_before.get(k) != v.settings for k, v in blocks.items())
    new_cfg = _render(blocks, global_settings) if (changed or global_settings) and blocks else old_cfg
    new_main = old_main
    if new_cfg != old_cfg and INCLUDE_LINE not in old_main:
        new_main = old_main.rstrip("\n") + ("\n\n" if old_main else "") + \
            f"// Fixes proposed by pipefix (keep this last so it overrides the defaults above)\n{INCLUDE_LINE}\n"
    return Patch({CONFIG_REL: (old_cfg, new_cfg), "nextflow.config": (old_main, new_main)},
                 fixes, advisories, global_settings)
